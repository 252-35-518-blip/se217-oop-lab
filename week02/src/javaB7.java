public class javaB7 {
      public static void main(String[] args) {
        int x = 1;
        switch (x) {
            case 1:
                System.out.println("New York");
                break;
            case 2:
                System.out.println("London");
                break;
            case 3:
                System.out.println("Edinburgh");
                break;
            default:
                System.out.println("Out of the World!");
        }
}
}
