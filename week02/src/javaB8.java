public class javaB8 {
     public static void main(String[] args) {
        int x;
        x = 54;

        System.out.println("Current value of x is: " + x++);
        System.out.println("Current value of x is: " + ++x);

        x = 32;
        System.out.println("Current value of x is: " + x--);
        System.out.println("Current value of x is: " + --x);



    }
}
